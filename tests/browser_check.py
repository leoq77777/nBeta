"""Run with a server at BASE_URL (default http://127.0.0.1:8765)."""
import os
from pathlib import Path
from urllib.parse import urljoin
from playwright.sync_api import sync_playwright, expect

BASE = os.environ.get('BASE_URL','http://127.0.0.1:8765')
OUT = Path('test-results')
OUT.mkdir(exist_ok=True)
checks = []
def check(condition, label):
    assert condition, label
    checks.append(label)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={'width':1512,'height':1100})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(BASE)
    page.wait_for_load_state('networkidle')
    check(page.locator('tbody tr').count()==30,'Rankings: 30 teams')
    page.get_by_role('button',name='Sort by Rating',exact=True).first.click()
    page.get_by_role('button',name='East',exact=True).click()
    check(page.locator('tbody tr').count()==15,'Conference works after sorting')
    page.get_by_role('button',name='League',exact=True).click()
    page.locator('#search').fill('Thunder')
    check(page.locator('tbody tr').count()==1,'Team search')
    page.locator('#search').fill('no-such-team')
    check(page.get_by_text('No teams match your search.').is_visible(),'Empty search state')
    page.locator('#search').fill('')
    page.get_by_role('button',name='Sort by #',exact=True).first.click()
    with page.expect_download() as dl:
        page.get_by_role('button',name='Export PNG ↗').click()
    dl.value.save_as(OUT/'rankings-share.png')
    check((OUT/'rankings-share.png').read_bytes()[:8]==b'\x89PNG\r\n\x1a\n','PNG export is an actual PNG')
    page.screenshot(path=str(OUT/'rankings-desktop.png'),full_page=True)
    page.locator('#theme').click()
    check(page.locator('html').get_attribute('data-theme')=='light','Light theme')
    page.reload();page.wait_for_load_state('networkidle')
    check(page.locator('html').get_attribute('data-theme')=='light','Theme persists after reload')
    page.screenshot(path=str(OUT/'rankings-light.png'),full_page=True)
    page.locator('#theme').click()
    page.locator('#tabs a[href="#wins"]').click()
    expect(page.locator('#tabs a[href="#wins"]')).to_have_attribute('aria-current','page')
    expect(page.locator('svg')).to_have_count(30)
    check(page.locator('svg').count()==30,'All 30 win distributions')
    page.locator('#win-filter').select_option('above')
    page.get_by_role('button',name='West',exact=True).click()
    check(0 < page.locator('svg').count() <=15,'Combined distribution and conference filter')
    page.locator('#win-filter').select_option('all')
    page.get_by_role('button',name='League',exact=True).click()
    page.screenshot(path=str(OUT/'wins-desktop.png'),full_page=True)
    page.locator('#tabs a[href="#ratings"]').click()
    expect(page.locator('#tabs a[href="#ratings"]')).to_have_attribute('aria-current','page')
    page.locator('#rating-team').select_option('UTA')
    check('Utah Jazz' in page.locator('.panel h3').first.inner_text(),'Rating team selector')
    check(page.locator('svg path').count()>30,'History lines and confidence band')
    page.locator('#tabs a[href="#games"]').click()
    expect(page.locator('#tabs a[href="#games"]')).to_have_attribute('aria-current','page')
    check(page.locator('.game-list article').count()>0,'Dated game cards')
    before=page.locator('#sandbox-result').inner_text()
    page.locator('#sandbox-adjust').fill('8')
    check(page.locator('#sandbox-result').inner_text()!=before,'Sandbox rating adjustment')
    page.locator('#sandbox-home').select_option('BOS')
    check('Choose two different teams' in page.locator('#sandbox-result').inner_text(),'Sandbox rejects self-matchup')
    page.locator('#sandbox-home').select_option('UTA')
    page.locator('#sandbox-neutral').check()
    check('Home spread' in page.locator('#sandbox-result').inner_text(),'Neutral court sandbox')
    check(abs(page.evaluate('studentTCDF(2,7.5)')-.9586)<.001,'Browser Student-t numeric reference')
    page.locator('#game-date').fill('2026-10-20')
    check(page.locator('.game-head').first.inner_text().endswith('FINAL'),'Completed game results')
    page.locator('#game-date').fill('2026-10-19')
    check(page.get_by_text('No games scheduled on this date.').is_visible(),'Empty date state')
    page.locator('#tabs a[href="#team"]').click()
    expect(page.locator('#tabs a[href="#team"]')).to_have_attribute('aria-current','page')
    check(page.locator('svg').count()==5,'Team: five analytical charts')
    for ab in page.locator('#team-select option').evaluate_all('(els)=>els.map(x=>x.value)'):
        page.locator('#team-select').select_option(ab)
        check(page.locator('svg').count()==5, f'Team deep link: {ab}')
    page.goto(BASE+'/#team/OKC');page.wait_for_load_state('networkidle')
    page.screenshot(path=str(OUT/'team-desktop.png'),full_page=True)
    page.locator('#tabs a[href="#model"]').click()
    expect(page.locator('#tabs a[href="#model"]')).to_have_attribute('aria-current','page')
    check(page.locator('a[download]').count()>=9,'Audit CSV downloads')
    check('not a multi-season out-of-sample backtest' in page.locator('#content').inner_text(),'Audit limitations visible')
    page.screenshot(path=str(OUT/'model-desktop.png'),full_page=True)
    for view in ['rankings','wins','ratings','games','team','model']:
        page.set_viewport_size({'width':390,'height':844})
        page.goto(BASE+'/#'+view);page.wait_for_load_state('networkidle')
        check(not page.evaluate('document.documentElement.scrollWidth > innerWidth'),f'No mobile document overflow: {view}')
        page.screenshot(path=str(OUT/f'{view}-mobile.png'),full_page=True)
    check(not errors, f'No JavaScript errors: {errors}')
    data_url=urljoin(BASE, page.locator('.site-foot a[download]').get_attribute('href'))
    expected_origin=os.environ.get('EXPECTED_DATA_ORIGIN')
    if expected_origin:
        check(data_url.startswith(expected_origin+'/'), 'CSV downloads use configured backend')
        check(page.evaluate('DATA_ROOT').startswith(expected_origin+'/snapshots/'), 'Browser uses pinned backend snapshot')
    for resource in ['teams','schedule','win_dist','players','backtest','calibration']:
        response=page.request.get(data_url.rsplit('/',1)[0]+'/'+resource+'.csv')
        check(response.ok and len(response.body())>10,f'CSV available: {resource}')
    failed=browser.new_page()
    failed.route('**/data/teams.json',lambda route:route.fulfill(status=503,body='Unavailable'))
    failed.goto(BASE);failed.wait_for_load_state('networkidle')
    check(failed.get_by_text('Snapshot unavailable').is_visible(),'Fetch failure UI')
    check(failed.get_by_role('button',name='Retry loading').is_visible(),'Retry available')
    browser.close()
print(f'PASS: {len(checks)} browser acceptance checks')
